-- =====================================================================
-- 编码发放流水留「路径快照」（T-CORE-10，EXP-20261108-46）
--
-- 规则（按业务确认）：
--   1. 码值只允许改名/停用，**不允许改 code_value**（改值等于换语义）；
--   2. 分类绑定变更后，已发编码不回溯（编码是既成事实，与蓝本一致），
--      因此发放流水要留**发放当时的路径快照**，便于追溯"这条码是按哪条路径发的"。
--
-- 例：分类 100102 当时绑定 `Kind_61a2…/1001/02/*`，后来改成别的码值，
--     `code_issue.generator_path` 仍保留旧路径，能解释历史编码的来源。
-- =====================================================================

ALTER TABLE code_issue ADD COLUMN IF NOT EXISTS generator_path varchar(500);

COMMENT ON COLUMN code_issue.generator_path IS
    '发放时的编码路径快照（种类/码值1/码值2/*）；不随分类绑定变更而改，对应蓝本 CODERES.GENERATORPATH';
