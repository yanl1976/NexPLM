-- =====================================================================
-- 物料「位置」字段（EXP-20261108-57）
--
-- 背景：蓝本物料申请页有「位置」栏（个人工作区/目录路径），与组织无关；
-- 账号本身已绑定组织，不需要再选组织。
--
-- 语义：自由文本的工作区/目录路径，如 `个人空间/2026/电气`，用于说明
--       该物料在个人/团队工作区中的归属位置，不参与权限判定。
-- =====================================================================

ALTER TABLE item_master ADD COLUMN IF NOT EXISTS location varchar(200);

COMMENT ON COLUMN item_master.location IS
    '位置（工作区/目录路径，自由文本）；与组织、权限无关，仅作归属说明';
